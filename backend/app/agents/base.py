"""Agent contract, shared pipeline state and the orchestrator.

Each agent has one job, reads and writes a shared `PipelineState`, and hands off to the
next agent. The orchestrator retries failed agents, uses an agent's fallback when retries
run out, and records every step in a trace so the whole run can be inspected.
"""
from __future__ import annotations

import asyncio
import time
from dataclasses import dataclass, field
from typing import Protocol


@dataclass
class PipelineState:
    seed: int
    raw_events: list[dict] | None = None      # supplied by a caller, or generated by the ingest agent
    events: list[dict] = field(default_factory=list)
    insights: list[dict] = field(default_factory=list)
    series: list[dict] = field(default_factory=list)
    final: dict = field(default_factory=dict)
    trace: list[dict] = field(default_factory=list)
    degraded: bool = False
    stats: dict = field(default_factory=dict)

    def log(self, agent: str, step: str, status: str = "ok", ms: float = 0.0, **detail) -> None:
        self.trace.append({"kind": "step", "agent": agent, "step": step, "status": status,
                           "ms": round(ms, 1), "detail": detail})

    def handoff(self, src: str, dst: str, **payload) -> None:
        self.trace.append({"kind": "handoff", "from": src, "to": dst, "payload": payload})


class Agent(Protocol):
    name: str
    critical: bool  # a critical agent failing aborts the run; others degrade gracefully

    async def run(self, state: PipelineState) -> None: ...


class Orchestrator:
    def __init__(self, agents: list[Agent], retries: int = 2) -> None:
        self.agents = agents
        self.retries = retries

    async def run(self, state: PipelineState) -> PipelineState:
        for i, agent in enumerate(self.agents):
            await self._run_agent(agent, state)
            if i + 1 < len(self.agents):
                state.handoff(agent.name, self.agents[i + 1].name, events=len(state.events),
                              insights=len(state.insights))
        return state

    async def _run_agent(self, agent: Agent, state: PipelineState) -> None:
        last: Exception | None = None
        for attempt in range(1, self.retries + 2):
            started = time.perf_counter()
            try:
                await agent.run(state)
                state.log(agent.name, "run", "ok", (time.perf_counter() - started) * 1000, attempt=attempt)
                return
            except Exception as exc:  # noqa: BLE001 - recovery boundary: any agent failure is retried
                last = exc
                state.log(agent.name, "run", "error", (time.perf_counter() - started) * 1000,
                          attempt=attempt, error=f"{type(exc).__name__}: {exc}")
                await asyncio.sleep(0.05 * attempt)
        fallback = getattr(agent, "fallback", None)
        if fallback is not None:
            await fallback(state)
            state.degraded = True
            state.log(agent.name, "fallback", "recovered")
            return
        if agent.critical:
            raise RuntimeError(f"{agent.name} failed after {self.retries + 1} attempts: {last}") from last
        state.degraded = True
        state.log(agent.name, "skipped", "degraded", error=str(last))
